create extension if not exists pgcrypto with schema extensions;
create table public.memos (
  id bigint generated by default as identity primary key,
  public_id uuid unique not null default extensions.gen_random_uuid(),
  owner_id uuid not null,
  title text not null,
  content text,
  created_at timestamptz not null default now()
);
alter table public.memos enable row level security;
revoke all on table public.memos from public, anon, authenticated;
create table public.memo_restore_backups (
  backup_key text primary key,
  public_id uuid unique not null,
  owner_id uuid not null,
  title text not null,
  content text not null,
  content_sha256 text not null check (content_sha256 ~ '^[0-9a-f]{64}$'),
  source_commit text not null check (source_commit ~ '^[0-9a-f]{40}$'),
  backed_up_at timestamptz not null default now()
);
create table public.memo_restore_audit (
  audit_id uuid primary key default extensions.gen_random_uuid(),
  restored_at timestamptz not null default now(),
  actor_id uuid not null,
  memo_public_id uuid not null,
  backup_sha256 text not null check (backup_sha256 ~ '^[0-9a-f]{64}$'),
  action text not null check (action = 'memo_restore')
);
alter table public.memo_restore_backups enable row level security;
alter table public.memo_restore_audit enable row level security;
revoke all on table public.memo_restore_backups, public.memo_restore_audit from public, anon, authenticated;
create schema byteback_recovery authorization postgres;
revoke all on schema byteback_recovery from public, anon, authenticated, service_role;
create table byteback_recovery.signing_key (
  singleton boolean primary key check (singleton),
  secret bytea not null check (octet_length(secret) = 32)
);
insert into byteback_recovery.signing_key(singleton, secret) values (true, extensions.gen_random_bytes(32));
create table byteback_recovery.initial_memo_backups (
  public_id uuid primary key, owner_id uuid not null, title text not null, content text not null,
  content_sha256 text not null check (content_sha256 ~ '^[0-9a-f]{64}$'),
  backed_up_at timestamptz not null, seal bytea not null check (octet_length(seal) = 32)
);
alter table byteback_recovery.signing_key enable row level security;
alter table byteback_recovery.initial_memo_backups enable row level security;
revoke all on all tables in schema byteback_recovery from public, anon, authenticated, service_role;